db=run(db,{type:'return/review',id:retId,status:'aprobada'});
assert.equal(stock(db,1).physical,before.physical+3,'aprobar sin recibir no debe reincorporar');
db=run(db,{type:'return/receive',id:retId});assert.equal(stock(db,1).physical,before.physical+5);assert.equal(db.orders[0].status,'devuelto');
fail(()=>run(db,{type:'return/receive',id:retId}));
