fail(()=>run(db,{type:'order/prepare',id:order.id}));
db=run(db,{type:'order/ready',id:order.id});
fail(()=>run(db,{type:'shipment/transition',id:ship.id,status:'despachado'}));
db=run(db,{type:'shipment/assign',id:ship.id,carrier:'Moto Logística Demo'});
db=run(db,{type:'shipment/transition',id:ship.id,status:'despachado'});
assert.equal(stock(db,1).physical,before.physical+3);assert.equal(stock(db,1).reserved,0);assert.equal(stock(db,1).available,before.available+3);assert.equal(db.orders[0].status,'enviado');
fail(()=>run(db,{type:'shipment/transition',id:ship.id,status:'despachado'}));
